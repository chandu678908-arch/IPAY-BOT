create table if not exists public.messages (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    role text not null,
    content text not null,
    created_at bigint not null
);
create index if not exists idx_messages_chat_created
    on public.messages (chat_id, created_at desc, id desc);

create table if not exists public.users (
    user_id bigint primary key,
    username text,
    first_name text,
    uid text not null,
    updated_at bigint not null
);
create index if not exists idx_users_uid on public.users (uid);

create table if not exists public.settings (
    key text primary key,
    value text not null,
    updated_at bigint not null
);

create table if not exists public.custom_faqs (
    key text primary key,
    title text not null,
    keywords jsonb not null,
    answer text not null,
    updated_at bigint not null
);

create table if not exists public.unanswered_questions (
    id bigint generated by default as identity primary key,
    question text not null,
    created_at bigint not null,
    reviewed boolean not null default false
);
create index if not exists idx_unanswered_question_time
    on public.unanswered_questions (question, created_at);
create index if not exists idx_unanswered_reviewed_id
    on public.unanswered_questions (reviewed, id desc);

alter table public.messages enable row level security;
alter table public.users enable row level security;
alter table public.settings enable row level security;
alter table public.custom_faqs enable row level security;
alter table public.unanswered_questions enable row level security;

revoke all on table public.messages, public.users, public.settings,
    public.custom_faqs, public.unanswered_questions from anon, authenticated;
grant usage on schema public to service_role;
grant all on table public.messages, public.users, public.settings,
    public.custom_faqs, public.unanswered_questions to service_role;
grant usage, select on all sequences in schema public to service_role;
