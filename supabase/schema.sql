-- Run this in the Supabase SQL Editor before enabling Supabase in the bot.
-- It is safe to rerun; the cooldown and request-history objects are additive.

create table if not exists public.messages (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    role text not null,
    content text not null,
    created_at bigint not null
);
create index if not exists idx_messages_chat_created
    on public.messages (chat_id, created_at desc, id desc);

create table if not exists public.users (
    user_id bigint not null,
    username text,
    first_name text,
    uid text not null,
    updated_at bigint not null,
    primary key (user_id, uid)
);
-- CREATE TABLE IF NOT EXISTS does not update an existing users table's keys.
-- This unique index makes the bot's ON CONFLICT (user_id, uid) upsert valid
-- for both new installs and the earlier schema with user_id as the primary key.
create unique index if not exists idx_users_user_uid
    on public.users (user_id, uid);
create index if not exists idx_users_uid on public.users (uid);

create table if not exists public.boost_cooldowns (
    user_id bigint primary key,
    last_requested_at bigint not null default 0
);

create table if not exists public.boost_requests (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    username text,
    first_name text,
    uid text not null,
    requested_at bigint not null,
    outcome text not null check (outcome in ('received', 'rate_limited')),
    remaining_seconds integer not null default 0,
    source text not null check (source in ('command', 'caption'))
);
create index if not exists idx_boost_requests_user_time
    on public.boost_requests (user_id, requested_at desc);

create or replace function public.reserve_boost_request(
    p_user_id bigint,
    p_now bigint,
    p_cooldown_seconds integer
)
returns integer
language plpgsql
as $function$
declare
    v_last_requested_at bigint;
    v_remaining integer;
begin
    insert into public.boost_cooldowns(user_id, last_requested_at)
    values (p_user_id, 0)
    on conflict (user_id) do nothing;

    select last_requested_at into v_last_requested_at
    from public.boost_cooldowns
    where user_id = p_user_id
    for update;

    v_remaining := p_cooldown_seconds - (p_now - v_last_requested_at);
    if v_remaining > 0 then
        return v_remaining;
    end if;

    update public.boost_cooldowns
    set last_requested_at = p_now
    where user_id = p_user_id;
    return 0;
end;
$function$;

create table if not exists public.settings (
    key text primary key,
    value text not null,
    updated_at bigint not null
);

create table if not exists public.custom_faqs (
    key text primary key,
    title text not null,
    keywords jsonb not null,
    answer text not null,
    updated_at bigint not null
);

create table if not exists public.unanswered_questions (
    id bigint generated by default as identity primary key,
    question text not null,
    created_at bigint not null,
    reviewed boolean not null default false
);
create index if not exists idx_unanswered_question_time
    on public.unanswered_questions (question, created_at);
create index if not exists idx_unanswered_reviewed_id
    on public.unanswered_questions (reviewed, id desc);

alter table public.messages enable row level security;
alter table public.users enable row level security;
alter table public.boost_cooldowns enable row level security;
alter table public.boost_requests enable row level security;
alter table public.settings enable row level security;
alter table public.custom_faqs enable row level security;
alter table public.unanswered_questions enable row level security;

revoke all on table public.messages, public.users, public.boost_cooldowns,
    public.boost_requests,
    public.settings, public.custom_faqs, public.unanswered_questions
    from anon, authenticated;
grant usage on schema public to service_role;
grant all on table public.messages, public.users, public.boost_cooldowns,
    public.boost_requests,
    public.settings, public.custom_faqs, public.unanswered_questions to service_role;
grant usage, select on all sequences in schema public to service_role;
revoke all on function public.reserve_boost_request(bigint, bigint, integer)
    from public, anon, authenticated;
grant execute on function public.reserve_boost_request(bigint, bigint, integer)
    to service_role;
